# some real data points
x_data = np.array([10, 20, 30, 40, 60, 80])
y_data = np.array([18, 35, 48, 58, 70, 75])

# basic curve shape
def fit_func(x, max_occ, ed50, hill):
    return max_occ * (x**hill) / (ed50**hill + x**hill)

# fit it
from scipy.optimize import curve_fit
popt, _ = curve_fit(fit_func, x_data, y_data, p0=[80, 25, 1.5])
max_occ, ed50, hill = popt

