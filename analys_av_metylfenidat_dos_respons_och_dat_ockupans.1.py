"""# Analys av Metylfenidat: Dos-respons och DAT-ockupans

Nedan följer den slutgiltiga, avskalade koden för att modellera och visualisera relationen mellan dos av metylfenidat och DAT-ockupans i hjärnan.

Modellen använder en Hill-ekvation för att anpassa en kurva till empirisk data för snabbverkande (IR) formuleringar och beräknar ett 95% konfidensintervall (skuggat område).

### Huvudresultat från anpassningen
* **Emax (Maximal ockupans):** ~77.02 %
* **ED50 (Dos för halva effekten):** ~11.79 mg

Diagrammet inkluderar även referenspunkter för långsamma (ER) formuleringar och mätningar vid 10 timmar, vilka ej använts i själva kurvanpassningen.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit
from scipy.stats import t

dose_ir = np.array([5.0, 10.0, 20.0, 40.0, 60.0, 60.0, 40.0])
occ_ir = np.array([12.0, 40.0, 54.0, 72.0, 74.0, 60.0, 71.5])
sd_ir = np.array([4.0, 12.0, 5.0, 3.0, 2.0, 11.0, 7.7])
n_ir = np.array([7, 7, 7, 7, 7, 10, 6])
se_ir = sd_ir / np.sqrt(n_ir)

dose_er = np.array([90.0])
occ_er = np.array([67.6])
sd_er = np.array([5.5])
n_er = np.array([6])

dose_off = np.array([36.0, 40.0])
occ_off = np.array([44.3, 34.8])
sd_off = np.array([11.8, 12.9])

def hill_model(d, emax, ed50, h):
    return emax * (d**h) / (ed50**h + d**h)

popt, pcov = curve_fit(
    hill_model,
    dose_ir,
    occ_ir,
    sigma=se_ir,
    absolute_sigma=True,
    p0=[80.0, 20.0, 1.5]
)

dof = len(dose_ir) - len(popt)
tval = t.ppf(0.975, dof)
perr = np.sqrt(np.diag(pcov))

print("--- Resultat ---")
names = ["Emax", "ED50", "h"]
for name, val, err in zip(names, popt, perr):
    low = val - tval * err
    high = val + tval * err
    print(f"{name}: {val:.2f} (95% CI: {low:.2f} till {high:.2f})")

x_fit = np.linspace(1, 100, 500)
y_fit = hill_model(x_fit, *popt)

def get_jacobian(d, emax, ed50, h):
    term = d**h
    denom = ed50**h + term
    df_demax = term / denom
    df_ded50 = -emax * term * (h * (ed50**(h - 1))) / (denom**2)
    df_dh = (emax * term * np.log(d) / denom) - (emax * term * ( (ed50**h)*np.log(ed50) + term*np.log(d) ) / (denom**2))
    return np.vstack([df_demax, df_ded50, df_dh]).T

sigmas = []
for x in x_fit:
    j = get_jacobian(x, *popt)
    sigmas.append(np.sqrt(np.dot(j, np.dot(pcov, j.T))[0][0]))

sigmas = np.array(sigmas)
y_low = y_fit - tval * sigmas
y_high = y_fit + tval * sigmas

plt.figure(figsize=(9.5, 6), dpi=150)

plt.plot(x_fit, y_fit, color="#1a5f7a", lw=2.5, label="Anpassad kurva (IR)")
plt.fill_between(x_fit, np.clip(y_low, 0, 100), np.clip(y_high, 0, 100),
                 color="#1a5f7a", alpha=0.15, label="95% KI")

plt.errorbar(dose_ir, occ_ir, yerr=sd_ir, fmt="o", color="#e05a47", ecolor="#e05a47",
             capsize=4, ms=6, label="IR-data")

plt.errorbar(dose_er, occ_er, yerr=sd_er, fmt="^", color="#d95f02", ecolor="#d95f02",
             capsize=4, ms=7, label="ER-data")

plt.errorbar(dose_off[0], occ_off[0], yerr=sd_off[0], fmt="o", mfc="none", mec="gray", ecolor="gray",
             capsize=4, ms=6, label="OROS (10h)")
plt.errorbar(dose_off[1], occ_off[1], yerr=sd_off[1], fmt="o", mfc="none", mec="gray", ecolor="gray",
             capsize=4, ms=6, label="Metadate (10h)")

plt.axhline(50, color="gray", linestyle="--", alpha=0.5, label="50% Ockupans")
plt.xlim(0, 100)
plt.ylim(0, 100)
plt.xlabel("Dos (mg)", fontsize=11)
plt.ylabel("DAT-ockupans (%)", fontsize=11)
plt.title("Metylfenidat: Dos vs. DAT-ockupans", fontsize=12, fontweight="bold")
plt.grid(True, linestyle="--", alpha=0.3)
plt.legend(loc="lower right", frameon=True, facecolor="white", edgecolor="none", shadow=False, fontsize=8.5)

plt.tight_layout()
plt.show()